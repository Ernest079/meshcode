// Model-level gate of the real study (pnpm bench:real; run bench:build first). For each prop it compares the
// artist's original with (a) meshcode's decompiled module and (b) the hand-written code imitation, with the
// thresholds registered before the imitations were written (research/bitacora.md, phase 4.2):
//   decompiled: silhouette IoU ≥ 0.999 in every view
//   imitation:  mean IoU ≥ 0.90, every view ≥ 0.85, colour error ≤ 12 levels
// Also reports authoring size: source lines (without blanks and comments) and bytes of each imitation.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { brotliCompressSync, constants } from 'node:zlib';
import { compareModels } from './compare.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const RESULTS = path.join(HERE, '../results');
const PROPS = ['crate', 'barrel', 'drone'];
const GATE = { decompiled: { min: 0.999 }, code: { mean: 0.9, min: 0.85, colour: 12 } };

const br = (/** @type {Buffer} */ b) => brotliCompressSync(b, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }).length;
const lines = (/** @type {string} */ src) => src.split('\n').filter((l) => l.trim() && !/^\s*(\/\/|\/\*\*?|\*)/.test(l)).length;
const size = async (/** @type {string} */ f) => { const b = await readFile(f); return { raw: b.length, br: br(b), lines: lines(b.toString()) }; };

/** @type {any[]} */ const rows = [];
for (const prop of PROPS) {
  const original = path.join(HERE, 'build', `${prop}.glb`);
  const decompiled = await compareModels(original, path.join(HERE, '../game/public/real/decompiled', `${prop}.js`));
  const code = await compareModels(original, path.join(HERE, 'models', `${prop}.js`), path.join(RESULTS, `figure-real-${prop}.png`));
  rows.push({
    prop, decompiled, code, source: await size(path.join(HERE, 'models', `${prop}.js`)),
    pass: {
      decompiled: decompiled.iou.min >= GATE.decompiled.min,
      code: code.iou.mean >= GATE.code.mean && code.iou.min >= GATE.code.min && code.colour.mean <= GATE.code.colour,
    },
  });
}
const kit = await size(path.join(HERE, 'models', 'kit.js'));

const f3 = (/** @type {number} */ x) => x.toFixed(3), ok = (/** @type {boolean} */ p) => (p ? '✅' : '❌');
const md = `# Real study — model-level gate

Generated by \`pnpm bench:real\` (${new Date().toISOString().slice(0, 10)}). Reference: the artist's original (bench/real/build/*.glb).
Silhouette IoU: 6 views at 256 px (meshcode fidelity). Colour error: mean |ΔRGB| over pixels both cover, 4 views at 384 px.
Gates (registered before writing the imitations): decompiled IoU ≥ ${GATE.decompiled.min} in every view; imitation mean IoU ≥ ${GATE.code.mean},
every view ≥ ${GATE.code.min}, colour error ≤ ${GATE.code.colour}.

| prop | delivery | IoU mean | IoU min | colour error | triangles (orig → copy) | pass |
|---|---|---:|---:|---:|---:|---|
${rows.flatMap((r) => [
  `| ${r.prop} | decompiled | ${f3(r.decompiled.iou.mean)} | ${f3(r.decompiled.iou.min)} | ${r.decompiled.colour.mean.toFixed(1)} | ${r.decompiled.tris.join(' → ')} | ${ok(r.pass.decompiled)} |`,
  `| ${r.prop} | code imitation | ${f3(r.code.iou.mean)} | ${f3(r.code.iou.min)} | ${r.code.colour.mean.toFixed(1)} | ${r.code.tris.join(' → ')} | ${ok(r.pass.code)} |`,
]).join('\n')}

## Authoring size of the imitations (source, before minification)

| file | lines of code | bytes | brotli |
|---|---:|---:|---:|
${rows.map((r) => `| models/${r.prop}.js | ${r.source.lines} | ${r.source.raw} | ${r.source.br} |`).join('\n')}
| models/kit.js (shared) | ${kit.lines} | ${kit.raw} | ${kit.br} |

Contact sheets (top: original, bottom: imitation): results/figure-real-{${PROPS.join(',')}}.png
`;
await writeFile(path.join(RESULTS, 'real-models.md'), md);
await writeFile(path.join(RESULTS, 'real-models.json'), JSON.stringify({ gate: GATE, kit, rows }, null, 2));
console.log(md);
